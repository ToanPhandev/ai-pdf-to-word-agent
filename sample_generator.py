"""Helper module to generate a realistic sample PDF and matching Word (.docx) template in memory."""

from __future__ import annotations

import io
from pathlib import Path

try:
    import pymupdf as fitz
except ImportError:  # pragma: no cover
    import fitz  # type: ignore[no-redef]
from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor


def generate_sample_pdf_bytes() -> bytes:
    """
    Programmatically generate a realistic 1-page Real Estate Title Report Summary PDF in memory.

    Returns:
        Raw bytes of the generated PDF document.
    """
    doc = fitz.open()
    page = doc.new_page(width=612, height=792)  # US Letter size (8.5 x 11 inches)

    # Draw header banner rectangle
    header_rect = fitz.Rect(36, 36, 576, 95)
    page.draw_rect(header_rect, color=(0.11, 0.23, 0.42), fill=(0.11, 0.23, 0.42))

    page.insert_text(
        fitz.Point(52, 62),
        "PACIFIC CREST TITLE & ESCROW SERVICES, INC.",
        fontsize=14,
        fontname="helv",
        color=(1, 1, 1),
    )
    page.insert_text(
        fitz.Point(52, 81),
        "PRELIMINARY TITLE REPORT & CLOSING VERIFICATION SUMMARY",
        fontsize=10,
        fontname="helv",
        color=(0.85, 0.91, 1.0),
    )

    body_lines = [
        ("DOCUMENT METADATA & FILING DETAILS", 12, True),
        ("Report Issue Status: CERTIFIED PRELIMINARY COMMITMENT", 10, False),
        ("Effective / Recording Date: 2026-11-15", 10, False),
        ("Assessor Parcel No. (APN): APN-4492-018-034-CA", 10, False),
        ("", 8, False),
        ("1. VESTED OWNER & SUBJECT PROPERTY", 12, True),
        ("Primary Owner / Buyer: Jonathan M. Sterling & Elena R. Sterling", 10, False),
        ("Property Address: 742 Evergreen Terrace, Suite 200, Pasadena, CA 91101", 10, False),
        (
            "Legal Description: Lot 18 of Tract No. 88412, in the City of Pasadena, County of Los Angeles, "
            "State of California, as per Map recorded in Book 914, Pages 42 through 45 inclusive of Maps.",
            10,
            False,
        ),
        ("", 8, False),
        ("2. UNDERWRITING & FINANCIAL ENCUMBRANCE SUMMARY", 12, True),
        ("Lender / Title Institution: First Republic Commercial Bank, N.A.", 10, False),
        ("Total Loan / Valuation Amount: $1,285,000.00", 10, False),
        ("Lien Priority: First Deed of Trust (Conventional Commercial-Residential Hybrid)", 10, False),
        ("Property Tax Status: Current - 1st Installment Paid in Full ($7,410.00)", 10, False),
        ("", 8, False),
        ("3. EXECUTIVE SUMMARY & CLOSING CONDITIONS", 12, True),
        (
            "Executive Summary: Title to the fee simple estate in the subject Pasadena parcel is vested in "
            "Jonathan M. Sterling and Elena R. Sterling, subject to a First Deed of Trust in favor of First "
            "Republic Commercial Bank, N.A. in the amount of $1,285,000.00. All municipal tax assessments under "
            "APN-4492-018-034-CA are paid current through the 2026 fiscal cycle with no unresolved mechanics liens.",
            10,
            False,
        ),
        ("", 10, False),
        ("4. CERTIFICATION NOTICE", 11, True),
        (
            "This report is issued solely for the facilitation of standardized escrow closing documentation "
            "and automated compliance verification.",
            9,
            False,
        ),
    ]

    y_cursor = 122
    for text, size, is_heading in body_lines:
        if not text:
            y_cursor += size
            continue

        if is_heading:
            page.draw_line(
                fitz.Point(40, y_cursor + 4),
                fitz.Point(572, y_cursor + 4),
                color=(0.78, 0.82, 0.88),
                width=0.8,
            )
            page.insert_text(
                fitz.Point(40, y_cursor),
                text,
                fontsize=size,
                fontname="helv",
                color=(0.11, 0.23, 0.42),
            )
            y_cursor += 22
        else:
            text_rect = fitz.Rect(44, y_cursor - 10, 568, y_cursor + 48)
            rc = page.insert_textbox(
                text_rect,
                text,
                fontsize=size,
                fontname="helv",
                color=(0.15, 0.15, 0.15),
            )
            lines_used = max(1, (len(text) // 82) + 1)
            y_cursor += max(18, lines_used * 15)

    # Footer
    page.draw_line(fitz.Point(36, 742), fitz.Point(576, 742), color=(0.8, 0.8, 0.8), width=0.5)
    page.insert_text(
        fitz.Point(40, 758),
        "Generated by AI PDF-to-Word Document Automation Agent | Confidential Sample Title Report",
        fontsize=8,
        fontname="helv",
        color=(0.45, 0.45, 0.45),
    )

    pdf_bytes = doc.tobytes()
    doc.close()
    return pdf_bytes


def generate_sample_docx_template_bytes() -> bytes:
    """
    Programmatically generate a styled Word (.docx) template with Jinja2 placeholders in memory.

    Placeholders included:
        {{ client_name }}
        {{ entity_address }}
        {{ reference_id }}
        {{ effective_date }}
        {{ institution_name }}
        {{ total_amount }}
        {{ legal_description }}
        {{ key_summary }}

    Returns:
        Raw bytes of the generated .docx template.
    """
    doc = Document()

    for section in doc.sections:
        section.top_margin = Inches(0.8)
        section.bottom_margin = Inches(0.8)
        section.left_margin = Inches(0.85)
        section.right_margin = Inches(0.85)

    # Header Title
    title_para = doc.add_paragraph()
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_para.add_run("STANDARD TITLE VERIFICATION & CLOSING FORM")
    title_run.bold = True
    title_run.font.size = Pt(16)
    title_run.font.color.rgb = RGBColor(28, 59, 107)

    subtitle_para = doc.add_paragraph()
    subtitle_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_run = subtitle_para.add_run(
        "Automated Compliance & Legal Intake Record (Preserved Formatting Template)"
    )
    sub_run.italic = True
    sub_run.font.size = Pt(10)
    sub_run.font.color.rgb = RGBColor(100, 116, 139)

    doc.add_paragraph()

    # Section 1: Summary Table
    sec1_heading = doc.add_heading("1. Primary Transaction & Parcel Record", level=2)
    for run in sec1_heading.runs:
        run.font.color.rgb = RGBColor(28, 59, 107)

    table = doc.add_table(rows=6, cols=2)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    rows_spec = [
        ("Primary Client / Vested Owner", "{{ client_name }}"),
        ("Subject Property Address", "{{ entity_address }}"),
        ("Reference / Parcel ID (APN)", "{{ reference_id }}"),
        ("Effective / Recording Date", "{{ effective_date }}"),
        ("Underwriting / Lending Institution", "{{ institution_name }}"),
        ("Total Transaction / Loan Amount", "{{ total_amount }}"),
    ]

    for idx, (label_text, tag_text) in enumerate(rows_spec):
        row_cells = table.rows[idx].cells
        label_run = row_cells[0].paragraphs[0].add_run(label_text)
        label_run.bold = True
        label_run.font.size = Pt(10.5)

        val_run = row_cells[1].paragraphs[0].add_run(tag_text)
        val_run.font.size = Pt(10.5)

    doc.add_paragraph()

    # Section 2: Legal Description
    sec2_heading = doc.add_heading("2. Verified Legal & Property Scope Description", level=2)
    for run in sec2_heading.runs:
        run.font.color.rgb = RGBColor(28, 59, 107)

    legal_para = doc.add_paragraph()
    legal_label = legal_para.add_run("Recorded Legal Description: ")
    legal_label.bold = True
    legal_para.add_run("{{ legal_description }}")

    # Section 3: Executive Summary
    sec3_heading = doc.add_heading("3. Executive Summary & Key Obligations", level=2)
    for run in sec3_heading.runs:
        run.font.color.rgb = RGBColor(28, 59, 107)

    summary_para = doc.add_paragraph()
    summary_para.add_run("{{ key_summary }}")

    # Section 4: Attestation Block
    doc.add_paragraph()
    sec4_heading = doc.add_heading("4. Human-in-the-Loop Verification & Sign-Off", level=2)
    for run in sec4_heading.runs:
        run.font.color.rgb = RGBColor(28, 59, 107)

    cert_para = doc.add_paragraph(
        "I hereby confirm that the extracted record for "
    )
    bold_client = cert_para.add_run("{{ client_name }}")
    bold_client.bold = True
    cert_para.add_run(" regarding reference ")
    bold_ref = cert_para.add_run("{{ reference_id }}")
    bold_ref.bold = True
    cert_para.add_run(" dated ")
    bold_date = cert_para.add_run("{{ effective_date }}")
    bold_date.bold = True
    cert_para.add_run(
        " has been reviewed and approved for closing issuance."
    )

    sig_para = doc.add_paragraph("\nAuthorized Reviewer Signature: ___________________________     Date: _______________")
    sig_para.runs[0].font.size = Pt(10)

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()


def generate_sample_files_bundle() -> tuple[bytes, bytes]:
    """Return (sample_pdf_bytes, sample_docx_template_bytes) generated in memory."""
    return generate_sample_pdf_bytes(), generate_sample_docx_template_bytes()


if __name__ == "__main__":
    pdf_data, docx_data = generate_sample_files_bundle()
    out_dir = Path(__file__).resolve().parent
    pdf_path = out_dir / "sample_title_report.pdf"
    docx_path = out_dir / "sample_closing_template.docx"
    pdf_path.write_bytes(pdf_data)
    docx_path.write_bytes(docx_data)
    print(f"Generated sample PDF ({len(pdf_data)} bytes): {pdf_path}")
    print(f"Generated sample Word template ({len(docx_data)} bytes): {docx_path}")
